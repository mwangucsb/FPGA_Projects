`timescale 1ns/1ps
`default_nettype none

module fifo_w1r1_tb;

    localparam DATA_WIDTH = 8;
    localparam ADDR_WIDTH = 3;

    // Testbench signals
    logic clk;
    logic reset;
    logic rd;
    logic wr;

    logic [DATA_WIDTH-1:0] w_data;
    logic [DATA_WIDTH-1:0] r_data;

    logic empty;
    logic full;

    // ------------------------------------------------
    // Clock
    // ------------------------------------------------
    always #5 clk = ~clk;

    // ------------------------------------------------
    // DUT
    // ------------------------------------------------
    fifo_w1r1 #(
        .DATA_WIDTH(DATA_WIDTH),
        .ADDR_WIDTH(ADDR_WIDTH)
    ) dut (
        .clk(clk),
        .reset(reset),
        .rd(rd),
        .wr(wr),
        .w_data(w_data),
        .r_data(r_data),
        .empty(empty),
        .full(full)
    );

    // ------------------------------------------------
    // Test
    // ------------------------------------------------
    initial begin

        // Initial values
        clk   = 0;
        reset = 1;
        rd    = 0;
        wr    = 0;
        w_data = 0;

        // --------------------------------------------
        // RESET
        // --------------------------------------------
        #10;
        reset = 0;

        // --------------------------------------------
        // WRITE 1
        // --------------------------------------------
        #10;
        w_data = 8'hA1;
        wr = 1;

        #10;
        wr = 0;

        // --------------------------------------------
        // WRITE 2
        // --------------------------------------------
        #10;
        w_data = 8'hB2;
        wr = 1;

        #10;
        wr = 0;

        // --------------------------------------------
        // WRITE 3
        // --------------------------------------------
        #10;
        w_data = 8'hC3;
        wr = 1;

        #10;
        wr = 0;

        // --------------------------------------------
        // READ 1
        // --------------------------------------------
        #10;
        rd = 1;

        #10;
        rd = 0;

        // --------------------------------------------
        // READ 2
        // --------------------------------------------
        #10;
        rd = 1;

        #10;
        rd = 0;

        // --------------------------------------------
        // READ 3
        // --------------------------------------------
        #10;
        rd = 1;

        #10;
        rd = 0;

        // --------------------------------------------
        // WRITE AND READ SIMULTANEOUSLY
        // --------------------------------------------
        #10;
        w_data = 8'hD4;
        wr = 1;
        rd = 1;

        #10;
        wr = 0;
        rd = 0;

        // --------------------------------------------
        // END
        // --------------------------------------------
        #20;
        $finish;

    end

endmodule

`default_nettype wire